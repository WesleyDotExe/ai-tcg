// Writes src/data/signatureApproved.ts: every signature line that passed the
// owner's fairness test at 2,500 seeds or more, read from the committed raw
// results of TODAY'S AGENT (owner 2026-10-19, answering session 48's
// question 2: "from now on, the approved signature list is read from today's
// agent's results"). Those are in progress/signature-fairness/agent41/,
// measured against the session-48 reference (signatureReference.json) with
// the agent session 41 rebuilt. The files directly in signature-fairness/
// are the session-32..35 agent's and no longer count; their reports still
// read them.
//
// The largest measurement of a line decides (session 35, owner 2026-10-15):
// a line that passed at 2,500 but fails at 10,000 is out; one that missed at
// 2,500 but passes at 10,000 is in. At equal seed counts the best result
// counts. The generator draws only from that list (owner 2026-10-05: "every
// candidate passes the fairness test before it is shown").
//
// Guardian 3/5 (`sig5-3x5-guardian`) fails its 10,000-game re-check with
// today's agent (report 033) and is off the list by that rule (owner
// 2026-10-19, option C); agents that already hold one keep it, since a
// stored card is rebuilt from its own spec, not looked up here.
//
// Every listed line records the fingerprint of the card as built now;
// test/agentGenerator.test.ts fails if a later data change makes a card
// differ from what was measured.
//
// Since session 50 each result line carries the fingerprint of the card it
// measured and the stamp of the reference it was measured against; a line
// whose stamps don't match today's card or reference is set aside as stale
// and printed (the rule is in signatureApprovedSelect.ts).
//
// When the measuring agent changes again, re-measure into a new subfolder
// and point AGENT_RESULTS at it, so two agents' numbers never mix.
//
// Usage (from engine/): npx tsx src/dev/signatureApprovedList.ts

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadReference, referenceRates, referenceStamp, type Reference } from "./signatureFairness.js";
import { selectApproved } from "./signatureApprovedSelect.js";
import { buildSignatureCard, onTable, signatureFingerprint, type SignatureSpec } from "../data/signatureMenu.js";

/** Today's agent's results, relative to progress/signature-fairness/. */
const AGENT_RESULTS = "agent41/";
const DIR = fileURLToPath(new URL(`../../../progress/signature-fairness/${AGENT_RESULTS}`, import.meta.url));
const OUT = fileURLToPath(new URL("../data/signatureApproved.ts", import.meta.url));

// Today's reference cut to each seed count asked for (undefined when it's
// shorter than the result).
const refs = new Map<number, Reference | undefined>();
const refAt = (seeds: number): Reference | undefined => {
  if (!refs.has(seeds)) {
    try {
      refs.set(seeds, loadReference(seeds));
    } catch {
      refs.set(seeds, undefined);
    }
  }
  return refs.get(seeds);
};
const { decisive, everPassed, stale } = selectApproved(
  readdirSync(DIR)
    .filter((f) => f.endsWith(".jsonl"))
    .map((name) => ({ name, text: readFileSync(DIR + name, "utf8") })),
  {
    fingerprint: (spec) => signatureFingerprint(buildSignatureCard(spec, { anyStats: true })),
    reference: (seeds) => {
      const ref = refAt(seeds);
      return ref && referenceStamp(ref);
    },
    refRates: (seeds) => {
      const ref = refAt(seeds);
      return ref && referenceRates(ref);
    },
  },
);
const passes = new Map([...decisive].filter(([, d]) => d.pass));

const rows = [...passes.entries()].sort(([a], [b]) => a.localeCompare(b));
const specText = (s: SignatureSpec) =>
  `{ ${Object.entries(s)
    .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    .join(", ")} }`;
const body = rows
  .map(([id, p]) => {
    const fp = signatureFingerprint(buildSignatureCard(p.spec, { anyStats: true }));
    return `  { id: ${JSON.stringify(id)}, spec: ${specText(p.spec)}, worst: ${p.worst.toFixed(4)}, seeds: ${p.seeds}, onTable: ${onTable(p.spec)}, fingerprint: ${JSON.stringify(fp)}, source: ${JSON.stringify(file(p.file))} },`;
  })
  .join("\n");
function file(f: string): string {
  return `progress/signature-fairness/${AGENT_RESULTS}${f}`;
}

writeFileSync(
  OUT,
  `// GENERATED by src/dev/signatureApprovedList.ts from progress/signature-fairness/${AGENT_RESULTS}*.jsonl.
// Don't edit by hand: re-run the script after new fairness results land.
//
// Every signature line that passed the owner's fairness test (2 points or
// less on every edge, paired, at 2,500 seeds or more; a line's largest
// measurement decides), measured with today's agent. The agent generator
// draws its signature candidates only from here.

import type { SignatureSpec } from "./signatureMenu.js";

export interface ApprovedSignatureLine {
  id: string;
  spec: SignatureSpec;
  /** Largest |change| over the twelve edges, as measured. */
  worst: number;
  seeds: number;
  /** False when the stat line is off the owner's table (allowed: owner
   * 2026-10-15, call 2). */
  onTable: boolean;
  /** signatureFingerprint of the card measured. */
  fingerprint: string;
  /** The raw results the pass is read from. */
  source: string;
}

export const APPROVED_SIGNATURE_LINES: readonly ApprovedSignatureLine[] = [
${body}
];
`,
);
console.log(`${rows.length} approved lines over ${new Set(rows.map(([, p]) => p.spec.ability)).size} options -> ${OUT}`);
for (const [id, p] of rows) console.log(`  ${id.padEnd(32)} worst ${(p.worst * 100).toFixed(2)} at ${p.seeds}  ${p.file}`);
for (const id of everPassed) {
  const d = decisive.get(id)!;
  if (!d.pass) console.log(`  OUT ${id.padEnd(28)} passed at a smaller seed count; fails at ${d.seeds} (worst ${(d.worst * 100).toFixed(2)})`);
}
for (const st of stale) console.log(`  STALE ${st.id.padEnd(26)} at ${st.seeds} in ${st.file}: ${st.why}`);
